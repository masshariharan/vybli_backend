'use strict';

/**
 * Writes the app's `lib/data/catalogue/city_districts.dart` — which official
 * district each catalogue city is in — by running every city's own
 * coordinates through `geo/district.service`.
 *
 *   node scripts/catalogue-districts.js <path to the app's cities.dart>
 *
 * The app needs this to turn the server's answer ("you are in Viluppuram
 * district") into the catalogue city that serves that district. Rerun it
 * whenever the catalogue or the boundaries change; it fails rather than
 * write a table with a city it could not place.
 */

const fs = require('fs');
const path = require('path');
const { districtAt } = require('../src/services/geo/district.service');

const citiesPath = process.argv[2];
if (!citiesPath) {
  console.error('usage: node scripts/catalogue-districts.js <app>/lib/data/catalogue/cities.dart');
  process.exit(1);
}

const src = fs.readFileSync(citiesPath, 'utf8');
const cities = [
  ...src.matchAll(
    /id: '([^']+)',\s*name: '([^']+)',\s*state: '([^']+)',[\s\S]*?latitude: ([\d.-]+),\s*longitude: ([\d.-]+)/g
  ),
].map((m) => ({ id: m[1], state: m[3], lat: Number(m[4]), lng: Number(m[5]) }));

const problems = [];
const rows = cities.map((c) => {
  const place = districtAt(c.lat, c.lng);
  if (!place?.district) problems.push(`${c.id}: no district`);
  else if (place.state !== c.state) problems.push(`${c.id}: ${c.state} vs ${place.state}`);
  return [c.id, place?.district];
});
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const out = path.join(path.dirname(citiesPath), 'city_districts.dart');
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
fs.writeFileSync(
  out,
  `// GENERATED by vybli_backend/scripts/catalogue-districts.js — do not edit.
//
// The official district each catalogue city is in, from India's 2021 district
// boundaries (see vybli_backend/src/assets/geo/NOTICE.md). The state is the
// city's own: the generator checks the two agree.

/// Catalogue city id → the district it is in.
const Map<String, String> kCityDistricts = {
${rows.map(([id, d]) => `  '${esc(id)}': '${esc(d)}',`).join('\n')}
};
`
);
console.log(`${rows.length} cities → ${out}`);
